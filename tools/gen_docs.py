def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def describe(schema):
    if "const" in schema:
        return "const `%s`" % json.dumps(schema["const"])
    if "enum" in schema:
        return "one of " + ", ".join("`%s`" % v for v in schema["enum"])
    kind = schema.get("type", "")
    parts = [kind if isinstance(kind, str) else "/".join(kind)]
    for key, label in (("minLength", "min length"), ("maxLength", "max length"), ("minItems", "min items"),
                       ("maxItems", "max items"), ("minimum", "minimum"), ("pattern", "pattern")):
        if key in schema:
            parts.append("%s %s" % (label, schema[key]))
    return ", ".join(p for p in parts if p)


def flatten(schema, prefix, required, rows):
    if "oneOf" in schema:
        for index, option in enumerate(schema["oneOf"], 1):
            basis = option.get("properties", {}).get("basis", {}).get("const")
            label = "%s (option %d%s)" % (prefix, index, ", basis " + basis if basis else "")
            rows.append((label, "object", "yes" if required else "no", schema.get("description", "")))
            flatten({k: v for k, v in option.items() if k != "description"}, prefix, None, rows)
        return
    if schema.get("type") == "object" and "properties" in schema:
        need = set(schema.get("required", []))
        for name, sub in schema["properties"].items():
            path = (prefix + "." if prefix else "") + name
            if sub.get("type") == "object" and "properties" in sub and set(sub["properties"]) == {"value", "unit"}:
                units_list = ", ".join("`%s`" % u for u in sub["properties"]["unit"]["enum"])
                rows.append((path, "quantity {value, unit}; unit one of " + units_list, "yes" if name in need else "no",
                             "value: " + sub["properties"]["value"]["description"]))
            elif sub.get("type") == "array" and isinstance(sub.get("items"), dict) and "properties" in sub["items"]:
                rows.append((path, "array of objects, " + describe(sub), "yes" if name in need else "no",
                             sub.get("description", "")))
                flatten(sub["items"], path + "[]", None, rows)
            elif "oneOf" in sub:
                flatten(sub, path, name in need, rows)
            elif sub.get("type") == "object" and "properties" in sub:
                rows.append((path, "object", "yes" if name in need else "no", sub.get("description", "")))
                flatten(sub, path, None, rows)
            else:
                rows.append((path, describe(sub), "yes" if name in need else "no", sub.get("description", "")))


def error_codes():
    codes = {}
    for name in ("foundation_refrigeration/tools.py", "foundation_refrigeration/thermo.py"):
        text = (ROOT / name).read_text()
        for code in re.findall(r'(?:ToolInputError|ThermoError)\("([a-z_]+)"', text):
            codes.setdefault(code, set()).add(name)
    codes.setdefault("invalid_quantity", set()).add("foundation_refrigeration/tools.py (UnitError, EvidenceError)")
    return {code: sorted(paths) for code, paths in sorted(codes.items())}


def wire_errors():
    text = (ROOT / "foundation_refrigeration_bridge/server.py").read_text()
    found = re.findall(r'(-32\d{3}), "([^"]+)"', text)
    found += [("-32603", m) for m in re.findall(r'else "([^"]+)"', text)]
    found = [(code, message + server.PROTOCOL + " (not MCP)" if message.endswith("expected ") else message)
             for code, message in found]
    return sorted({(int(code), message.strip()) for code, message in found}, key=lambda r: (-r[0], r[1]))


def catalog():
    tools = tool_definitions()
    inventory = json.dumps(tools, ensure_ascii=True, allow_nan=False, sort_keys=True, separators=(",", ":"))
    out = ["# Tool catalog", "",
           "Generated by `%s` from `foundation_refrigeration_bridge/schemas.py`, `foundation_refrigeration/tools.py`, "
           "`foundation_refrigeration/thermo.py` and `foundation_refrigeration_bridge/server.py`. Do not edit by hand; "
           "`tests/test_docs_trace.py` fails when this file is stale." % COMMAND, "",
           "| Item | Value |", "|---|---|",
           "| Foundation version | `%s` |" % __version__,
           "| Bridge protocol | `%s` |" % server.PROTOCOL,
           "| Tools | %d |" % len(tools),
           "| Canonical inventory SHA-256 | `%s` |" % hashlib.sha256(inventory.encode("ascii")).hexdigest(),
           "", "The inventory digest is SHA-256 over `json.dumps(tool_definitions(), ensure_ascii=True, "
           "allow_nan=False, sort_keys=True, separators=(\",\", \":\"))`. This is the encoding the host uses to pin the "
           "inventory.", "",
           "Every tool call returns `structuredContent` with `tool`, `assessment`, `formal_proof: false`, "
           "`runtime_goal_acceptance: false` and a `receipt`. Receipt fields are listed in the "
           "[data dictionary](../../data/data-dictionary.md#3-records-and-files).", ""]
    for tool in tools:
        name = tool["name"]
        out += ["## `%s`" % name, "", cell(tool["description"]), "",
                "| Argument | Type and limits | Required | Notes |", "|---|---|---|---|"]
        rows = []
        flatten(tool["inputSchema"], "", None, rows)
        out += ["| `%s` | %s | %s | %s |" % (cell(a), cell(b), c, cell(d)) for a, b, c, d in rows]
        out += ["", "Success assessments: " + ", ".join("`%s`" % a for a in ASSESSMENTS[name])
                + ". Failure assessment: `tool_error`.", ""]
    out += ["## Tool error codes", "",
            "A tool error is a normal JSON-RPC result with `isError: true`, assessment `tool_error`, "
            "`receipt.status: \"error\"`, `receipt.result: null`, empty `evidence` and `data_sources`, the three common "
            "limitations, and `receipt.error.code` from this table.", "",
            "| Code | Raised in |", "|---|---|"]
    out += ["| `%s` | %s |" % (code, ", ".join("`%s`" % p if "(" not in p else p for p in paths))
            for code, paths in error_codes().items()]
    out += ["", "## JSON-RPC error codes", "",
            "Returned as a JSON-RPC `error` object. No receipt or Evidence is produced.", "",
            "| Code | Message |", "|---|---|"]
    out += ["| %d | %s |" % (code, cell(message)) for code, message in wire_errors()]
    out += ["", "## Common limitations", "", "Every receipt, success or error, starts its `limitations` list with:", ""]
    out += ["- " + text for text in COMMON_LIMITATIONS]
    out += ["", "## Bridge limits", "", "| Limit | Value |", "|---|---|"]
    for label, value in (("Input frame bytes", server.MAX_FRAME_BYTES), ("Output frame bytes", server.MAX_OUTPUT_BYTES),
                         ("JSON nesting depth", server.MAX_JSON_DEPTH), ("JSON nodes", server.MAX_JSON_NODES),
                         ("String characters", server.MAX_STRING_CHARS), ("Number literal characters",
                                                                          server.MAX_NUMBER_CHARS),
                         ("Integer digits", 15), ("Request id characters", server.MAX_ID_CHARS),
                         ("Request id integer absolute value", server.MAX_ID_INTEGER),
                         ("Quantity magnitude (domain)", "%g" % units.MAX_MAGNITUDE)):
        out.append("| %s | %s |" % (label, value))
    if tuple(t["name"] for t in tools) != TOOL_NAMES:
        raise SystemExit("tool order differs from TOOL_NAMES")
    return "\n".join(out) + "\n"


def load(name):
    raw = (DATA_DIR / name).read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def reference_data():
    out = ["# Reference data provenance", "",
           "Generated by `%s` from the JSON files in `foundation_refrigeration/data/` and `golden/`. Do not edit by "
           "hand; `tests/test_docs_trace.py` fails when this file is stale. Explanations of each column are in the "
           "[data dictionary](data-dictionary.md#4-reference-data-provenance)." % COMMAND, "",
           "## Projection files", "", "| File | Schema | Version | Owner module | SHA-256 |", "|---|---|---|---|---|"]
    files = sorted(p.name for p in DATA_DIR.glob("*.json"))
    for name in files:
        doc, sha = load(name)
        out.append("| `%s` | `%s` | %s | `%s` | `%s` |" % (name, doc["schema"], doc["version"], doc["owner"], sha))
    out += ["", "## Saturation tables", "",
            "All rows are stored in `degC, kPa(a), kPa(a), J/kg, J/kg` (temperature, bubble pressure, dew pressure, "
            "liquid enthalpy, vapour enthalpy). They were converted from generator output in `degF, psia, psia, J/kg, "
            "J/kg` with `degC = (degF - 32) / 1.8` and `kPa(a) = psia * 6.894757293168361`.", "",
            "| Table | Fluid | Kind | Composition | Source | Edition | CoolProp fluid / backend / reference state | "
            "Range (degC) | Rows | Lookup error (K) | Evidence |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name in files:
        if not name.startswith("refrigerant-saturation."):
            continue
        body = load(name)[0]["data"]
        out.append("| `%s` | %s | %s | %s | %s | %s | %s / %s / %s | %.4f to %.4f | %d | %.6f | %s, %s |" % (
            body["id"], cell(body["name"]), body["kind"], cell(body["composition"]), body["source"], body["edition"],
            body["coolpropFluid"], body["propertyBackend"], body["referenceState"], body["range"]["min_temp_c"],
            body["range"]["max_temp_c"], len(body["rows"]), body["interpolation"]["error_k"],
            body["evidence"]["basis"]["kind"], body["evidence"]["status"]))
    sample = load("refrigerant-saturation.nh3.json")[0]["data"]
    out += ["", "Generator command recorded in every table: `%s`. Generator script SHA-256: `%s`. The generator "
            "scripts are not shipped in this repository." % (cell(sample["evidence"]["basis"]["generator"]),
                                                              sample["generator"]["sha256"]),
            "", "Interpolation: %s. Error scope: %s." % (sample["interpolation"]["method"],
                                                          sample["interpolation"]["error_scope"]),
            "", "Limitations recorded in every table:", ""]
    out += ["- " + text for text in sample["limitations"]]
    limits = load("exposure-limits.json")[0]["data"]
    out += ["", "## Exposure limits (`exposure-limits.json`)", "",
            "Substance: %s (%s), CAS %s. Scope: %s" % (limits["substance"]["name"], limits["substance"]["formula"],
                                                       limits["substance"]["cas"], limits["scope"]), "",
            "| ID | Issuer | Kind | Value (ppm) | Value (mg/m3) | Averaging | Legal status | Source | Edition | URL | "
            "Retrieved | Evidence |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for row in limits["limits"]:
        basis = row["evidence"]["basis"]
        mass = row["mass_concentration"]
        out.append("| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            row["id"], row["issuer"], row["kind"], row["concentration"]["value"], "none" if mass is None else
            mass["value"], row["averaging"], row["legal_status"], cell(basis["source"]), cell(basis["version"]),
            basis["url"], basis["retrievedOn"], row["evidence"]["status"]))
    out += ["", "Recorded gaps:", ""]
    out += ["- `%s` (%s): %s" % (g["id"], ", ".join(g["items"]), g["reason"]) for g in limits["gaps"]]
    psm = load("psm-thresholds.json")[0]["data"]
    out += ["", "## Process-safety thresholds (`psm-thresholds.json`)", "", "Scope: " + psm["scope"], "",
            "| Framework | Substance | CAS | Threshold | Comparison | Threshold source | Edition | Retrieved | Evidence |",
            "|---|---|---|---|---|---|---|---|---|"]
    for rule in psm["rules"]:
        basis = rule["threshold_evidence"]["basis"]
        out.append("| `%s` | %s | %s | %d %s | %s | %s | %s | %s | %s |" % (
            rule["framework"], rule["substance"], rule["cas"], rule["threshold_lb"], rule["unit"], rule["comparison"],
            cell(basis["source"]), cell(basis["version"]), basis["retrievedOn"], rule["threshold_evidence"]["status"]))
    taxonomy = load("plant-taxonomy.json")[0]["data"]
    out += ["", "## Plant taxonomy (`plant-taxonomy.json`)", "",
            "| Item | Count |", "|---|---|",
            "| Canonical kinds | %d |" % len(taxonomy["kinds"]), "| Aliases | %d |" % len(taxonomy["aliases"]),
            "| Alias notes | %d |" % len(taxonomy["alias_notes"]), "| Line-service codes | %d |" %
            len(taxonomy["line_services"]), "| Legacy lists | %d |" % len(taxonomy["legacy_lists"]),
            "", "Normalisation: %s. Evidence: %s, %s (%s)" % (
                taxonomy["normalisation"], taxonomy["evidence"]["basis"]["kind"], taxonomy["evidence"]["status"],
                cell(taxonomy["evidence"]["basis"]["note"]))]
    decisions = load("open-decisions.json")[0]["data"]
    out += ["", "## Open decisions (`open-decisions.json`)", "", "Rule: " + decisions["rule"], "",
            "| ID | Topic | Positions | Status |", "|---|---|---|---|"]
    out += ["| `%s` | %s | %d | %s |" % (d["id"], cell(d["topic"]), len(d["positions"]), d["evidence"]["status"])
            for d in decisions["decisions"]]
    out += ["", "## Golden reference files (`golden/`)", "", "| File | Schema | Oracle or source | Generated on | Points |",
            "|---|---|---|---|---|"]
    for path in sorted((ROOT / "golden").glob("*.json")):
        doc = json.loads(path.read_text())
        if "by_temperature" in doc:
            count = len(doc["by_temperature"]) + len(doc["by_pressure"]) + len(doc["census_nh3_anchor_points"])
            oracle, when = doc["oracle"], doc["generated_on"]
        else:
            count = sum(len(f.get("byTemp", [])) + len(f.get("byPressure", [])) for f in doc["fluids"].values())
            oracle, when = doc["generatedBy"], doc["generated_on"]
        out.append("| `%s` | `%s` | %s | %s | %d |" % (path.name, doc.get("schema", ""), cell(oracle), when, count))
    return "\n".join(out) + "\n"


def main(argv):
    check = argv[1:] == ["--check"]
    if argv[1:] not in ([], ["--check"]):
        print("usage: python -B tools/gen_docs.py [--check]")
        return 2
    stale = []
    for path, text in ((CATALOG, catalog()), (DATA, reference_data())):
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text)
            print("wrote " + path.relative_to(ROOT).as_posix())
    for name in stale:
        print("stale: " + name)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
